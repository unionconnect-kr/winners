import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const mobile = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const apk = resolve(process.argv[2] || 'android/app/build/outputs/apk/debug/app-debug.apk');
const sdk = process.env.ANDROID_HOME || process.env.ANDROID_SDK_ROOT;
assert.ok(sdk, 'Set ANDROID_HOME to the SDK directory.');
const buildTools = resolve(sdk, 'build-tools/36.0.0');
const run = (name, args) => execFileSync(resolve(buildTools, name), args, { encoding: 'utf8' });
const unpack = path => execFileSync('unzip', ['-p', apk, path], { encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 });
const badging = run('aapt', ['dump', 'badging', apk]);
assert.match(badging, /package: name='kr\.co\.manee\.app\.staging'/);
assert.match(badging, /sdkVersion:'24'/);
assert.match(badging, /targetSdkVersion:'36'/);
const permissions = run('aapt', ['dump', 'permissions', apk]);
assert.match(permissions, /android\.permission\.ACCESS_FINE_LOCATION/);
assert.match(permissions, /android\.permission\.ACCESS_COARSE_LOCATION/);
assert.doesNotMatch(permissions, /RECORD_AUDIO|READ_CONTACTS|READ_CALENDAR|WRITE_CALENDAR|ACCESS_BACKGROUND_LOCATION|POST_NOTIFICATIONS|READ_MEDIA|READ_EXTERNAL_STORAGE|WRITE_EXTERNAL_STORAGE|AD_ID|BILLING/);
const manifest = run('aapt', ['dump', 'xmltree', apk, 'AndroidManifest.xml']);
assert.match(manifest, /android:allowBackup[^\n]*=\(type 0x12\)0x0/);
assert.match(manifest, /android:usesCleartextTraffic[^\n]*=\(type 0x12\)0x0/);
const environments = JSON.parse(readFileSync(resolve(mobile, '../config/environments.json'), 'utf8'));
const info = JSON.parse(unpack('assets/public/build-info.json'));
assert.equal(info.platform, 'android');
assert.equal(info.environment, 'staging');
assert.equal(info.projectRef, environments.staging.projectRef);
const appConfig = unpack('assets/public/app-config.js');
assert.ok(!appConfig.includes(environments.production.projectRef), 'Production backend is packaged.');
const plugins = JSON.parse(unpack('assets/capacitor.plugins.json'));
assert.deepEqual(plugins.map(p => p.pkg), ['@capacitor/geolocation']);
assert.doesNotMatch(unpack('assets/public/native.js'), /ManeeStoreKit|PushNotifications|ios-push|ios-billing/);
run('apksigner', ['verify', '--verbose', apk]);
console.log('Verified signed staging APK: Android 7+, target API 36, staging backend, foreground location, no billing/push/audio/contact/calendar permissions.');
console.log(permissions.trim());
